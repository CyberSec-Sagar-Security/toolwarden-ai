"""Assembles the normalized dataset from all sources, writes it to
datasets/processed/ (gitignored — code here is tracked, data isn't), and
writes a human-readable report to datasets/REPORT.md with sizes, class
balance, and a leakage check between the trainable pool and the held-out
novel-attack split.

Run with: python -m toolwarden.datasets.build
"""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from toolwarden.datasets import agentdojo_light, injecagent
from toolwarden.datasets.schema import DatasetRecord, Label, Split

REPO_ROOT = Path(__file__).resolve().parents[3]
RAW_DIR = REPO_ROOT / "datasets" / "raw" / "injecagent"
PROCESSED_PATH = REPO_ROOT / "datasets" / "processed" / "records.jsonl"
REPORT_PATH = REPO_ROOT / "datasets" / "REPORT.md"


def assemble() -> list[DatasetRecord]:
    injecagent.download_raw(RAW_DIR)
    records = injecagent.normalize(RAW_DIR)
    records += agentdojo_light.normalize()
    return records


def write_processed(records: list[DatasetRecord], path: Path = PROCESSED_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for record in records:
            f.write(json.dumps(record.to_dict()) + "\n")


def _find_text_overlap(trainable: list[DatasetRecord], held_out: list[DatasetRecord]) -> set[str]:
    trainable_texts = {r.text.strip() for r in trainable}
    held_out_texts = {r.text.strip() for r in held_out}
    return trainable_texts & held_out_texts


def build_report(records: list[DatasetRecord]) -> str:
    by_split = Counter(r.split for r in records)
    by_source = Counter(r.source for r in records)
    by_label_per_split: dict[Split, Counter] = {}
    for split in Split:
        split_records = [r for r in records if r.split == split]
        by_label_per_split[split] = Counter(r.label for r in split_records)

    trainable = [r for r in records if r.split in (Split.TRAIN, Split.TEST)]
    held_out = [r for r in records if r.split == Split.HELD_OUT_NOVEL]
    overlap = _find_text_overlap(trainable, held_out)

    lines = ["# Dataset Report", "", "Generated by `src/toolwarden/datasets/build.py`. See docs/datasets.md for source rationale.", ""]

    lines.append("## Totals")
    lines.append("")
    lines.append(f"- Total records: {len(records)}")
    for source, count in by_source.items():
        lines.append(f"  - {source}: {count}")
    lines.append("")

    lines.append("## Split sizes and class balance")
    lines.append("")
    lines.append("| Split | Total | Injection | Benign |")
    lines.append("|---|---|---|---|")
    for split in Split:
        total = by_split.get(split, 0)
        counts = by_label_per_split[split]
        lines.append(
            f"| {split.value} | {total} | {counts.get(Label.INJECTION, 0)} | "
            f"{counts.get(Label.BENIGN, 0)} |"
        )
    lines.append("")

    lines.append("## Held-out split leakage check")
    lines.append("")
    if overlap:
        lines.append(
            f"**FAILED:** {len(overlap)} exact text string(s) appear in both the trainable pool "
            "(train+test) and the held-out novel-attack pool. This must be zero before training."
        )
    else:
        lines.append(
            "**Clean.** Zero exact text overlap between the trainable pool (train+test, InjecAgent) "
            "and the held-out novel-attack pool (AgentDojo). The two pools come from structurally "
            "disjoint sources by construction (see docs/datasets.md), so this checks for accidental "
            "duplication, not just the intended source split."
        )
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    records = assemble()
    write_processed(records)
    report = build_report(records)
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(report)
    print(f"\nProcessed records written to: {PROCESSED_PATH} (gitignored)")
    print(f"Report written to: {REPORT_PATH}")


if __name__ == "__main__":
    main()
